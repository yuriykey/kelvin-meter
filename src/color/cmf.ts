export const CMF_SAMPLE_COUNT = CIE_1931_2DEG.length / 3;
export const CMF_END_NM = CMF_START_NM + (CMF_SAMPLE_COUNT - 1) * CMF_STEP_NM;

export function cmfWavelength(index: number): number {
  return CMF_START_NM + index * CMF_STEP_NM;
}

export function cmfAt(index: number): readonly [number, number, number] {
  const base = index * 3;
  return [CIE_1931_2DEG[base]!, CIE_1931_2DEG[base + 1]!, CIE_1931_2DEG[base + 2]!];
}
